# This is a module (Python file with functions)

# use type hints for parameters and return type
def add(a: float, b: float) -> float:
    """This function gets 2 numbers and returns their sum"""
    return a + b


def sub(a: float, b: float) -> float:
    """Gets 2 numbers and return the subtract result"""
    return a - b


def mul(a: float, b: float) -> float:
    """Gets 2 numbers and return the multiplication result"""
    return a * b


def div(a: float, b: float) -> float:
    """Gets 2 numbers and return the division result"""
    return a / b
